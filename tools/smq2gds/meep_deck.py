"""Write a self-contained MEEP FDTD script for an exported MMI.

The script reads the GDS written by smq2gds (mp.get_GDSII_prisms), so the FDTD sees exactly the mask polygons,
and needs only `pymeep` (conda-forge) — no gdsfactory in that environment.

    conda create -n mp -c conda-forge pymeep && conda activate mp
    python design_meep.py --gds design.gds            # 3D, resolution 20 px/µm
    python design_meep.py --gds design.gds --2d       # 2D with the slab effective index (quick look)
"""
from __future__ import annotations

import json
from pathlib import Path

from .design import n_core, n_ox

TEMPLATE = r'''#!/usr/bin/env python
"""MEEP FDTD check of {title}
Generated by smq2gds from smq-design/1 — geometry comes from the GDS, materials from the game's n(λ) at λc.
Reports per-port TE0 transmission, excess loss and imbalance at the game's wavelengths and writes <gds>.meep.json.
"""
import argparse, json, math
import numpy as np
import meep as mp

D = json.loads(r"""{design}""")
G, PF = D["geometry"], D["platform"]
N_CORE, N_OX = {n_core}, {n_ox}          # at λc, from the same Sellmeier fits the game uses

ap = argparse.ArgumentParser()
ap.add_argument("--gds", required=True)
ap.add_argument("--layer", type=int, default={layer})
ap.add_argument("--res", type=float, default=20, help="pixels per µm (≥ 20 for Si, 12 for SiN)")
ap.add_argument("--2d", dest="two_d", action="store_true", help="2D with the slab TE0 effective index")
ap.add_argument("--out", default=None)
a = ap.parse_args()

t, lc = PF["core_t_um"], G["lc_um"]
W, L, s, w0, Lt = G["W_um"], G["L_um"], G["s_um"], G["w_io_um"], G["taper_len_um"]
lams = G["lams_um"]


def slab_neff(n1, n0, d, lam):  # symmetric slab TE0 (for --2d)
    k0, lo, hi = 2 * math.pi / lam, n0 + 1e-9, n1 - 1e-9
    for _ in range(80):
        m = 0.5 * (lo + hi); ka = k0 * math.sqrt(n1 * n1 - m * m); ga = k0 * math.sqrt(m * m - n0 * n0)
        f = 1e9 if ka * d / 2 >= math.pi / 2 else ka * math.tan(ka * d / 2) - ga
        lo, hi = (m, hi) if f > 0 else (lo, m)
    return 0.5 * (lo + hi)


n_c = slab_neff(N_CORE, N_OX, t, lc) if a.two_d else N_CORE
core, clad = mp.Medium(index=n_c), mp.Medium(index=N_OX)
pad_xy, pad_z, dpml = 1.0, 1.2 if PF["mat"] == "si" else 1.8, 1.0
x0, x1 = -Lt - pad_xy, L + Lt + pad_xy
sx, sy = x1 - x0 + 2 * dpml, W + 2 * pad_xy + 2 * dpml + 1.0
sz = 0 if a.two_d else t + 2 * pad_z + 2 * dpml
zc = 0 if a.two_d else t / 2
cell = mp.Vector3(sx, sy, sz)
center = mp.Vector3((x0 + x1) / 2, 0, zc)
geometry = mp.get_GDSII_prisms(core, a.gds, a.layer, -5 if a.two_d else 0, 5 if a.two_d else t)

fmin, fmax = 1 / max(lams), 1 / min(lams)
fc, df = 1 / lc, max(fmax - fmin, 0.1 / lc) * 1.5
yin = 0.0 if G["type"] == "1x2" else -s / 2
src_x, mon_in_x, mon_out_x = -Lt + 0.3, -Lt + 0.6, L + Lt - 0.3
hz = 0 if a.two_d else t + 2 * 0.9
parity = mp.EVEN_Z   # TE-like (E in the chip plane): meep's EVEN_Z in 2D and for the z-symmetric 3D stack; band 1 = TE0
src = [mp.EigenModeSource(mp.GaussianSource(fc, fwidth=df), center=mp.Vector3(src_x, yin, zc), size=mp.Vector3(0, min(s, w0 + 1.2), hz),
                          eig_band=1, eig_parity=parity, eig_match_freq=True)]
sim = mp.Simulation(cell_size=cell, geometry_center=center, boundary_layers=[mp.PML(dpml)], geometry=geometry, default_material=clad,
                    sources=src, resolution=a.res)
nf = max(len(lams), 21)
freqs = np.linspace(fmin, fmax, nf) if len(lams) > 1 else np.array([fc])
win = lambda y: mp.FluxRegion(center=mp.Vector3(mon_out_x, y, zc), size=mp.Vector3(0, s, hz))
m_in = sim.add_mode_monitor(freqs, mp.FluxRegion(center=mp.Vector3(mon_in_x, yin, zc), size=mp.Vector3(0, min(s, w0 + 1.2), hz)))
m_p, m_m = sim.add_mode_monitor(freqs, win(+s / 2)), sim.add_mode_monitor(freqs, win(-s / 2))
sim.run(until_after_sources=mp.stop_when_fields_decayed(50, mp.Ez if a.two_d else mp.Ey, mp.Vector3(mon_out_x, s / 2, zc), 1e-6))

kw = dict(eig_parity=parity)
a_in = sim.get_eigenmode_coefficients(m_in, [1], **kw).alpha[0, :, 0]
a_p = sim.get_eigenmode_coefficients(m_p, [1], **kw).alpha[0, :, 0]
a_m = sim.get_eigenmode_coefficients(m_m, [1], **kw).alpha[0, :, 0]
Pin = np.abs(a_in) ** 2
Tp, Tm = np.abs(a_p) ** 2 / Pin, np.abs(a_m) ** 2 / Pin
rows = []
pred = {{round(r["lam_um"], 4): r for r in G.get("predicted_per_lam", [])}}
for lam in lams:
    i = int(np.argmin(np.abs(freqs - 1 / lam)))
    el, imb = -10 * math.log10(Tp[i] + Tm[i]), 10 * math.log10(Tp[i] / Tm[i])
    rows.append(dict(lam_um=lam, T_plus=float(Tp[i]), T_minus=float(Tm[i]), el_dB=el, imb_dB=imb))
    p = pred.get(round(lam, 4))
    print(f"λ {{lam * 1000:.0f}} nm: EL {{el:.3f}} dB, imbalance {{imb:+.3f}} dB" + (f"   (game: {{p['el_dB']:.3f}} / {{p['imb_dB']:+.3f}} dB)" if p else ""))
out = a.out or a.gds.rsplit(".", 1)[0] + (".meep2d.json" if a.two_d else ".meep.json")
json.dump(dict(schema="smq-check/1", solver="meep FDTD " + ("2D slab-EIM" if a.two_d else "3D"), resolution=a.res, rows=rows), open(out, "w"), indent=1)
print("→", out)
'''


def write(d: dict, path: str) -> None:
    g, pf = d["geometry"], d["platform"]
    if g["pcell"] != "mmi":
        raise SystemExit("--meep: MMI designs only (a 16-cm spiral is not an FDTD problem; use --sim mode)")
    lc = g["lc_um"]
    layer = 1 if pf["mat"] == "si" else 34
    src = TEMPLATE.format(
        title=f"{pf['id']} {d['level']['id']} {d['level']['device']}",
        design=json.dumps(d, ensure_ascii=False),
        n_core=f"{n_core(pf['mat'], lc):.6f}",
        n_ox=f"{n_ox(lc):.6f}",
        layer=layer,
    )
    Path(path).write_text(src, encoding="utf-8")
